static int mcpdf_lookup_variant(const McpdfVariant *table, int n, int rows,
                                 int *out_ec, int *out_bits)
{
    for (int i = 0; i < n; i++) {
        if (table[i].rows == rows) {
            *out_ec = table[i].ec;
            if (out_bits) *out_bits = table[i].bits;
            return 1;
        }
    }
    return 0;
}

typedef struct {
    int cw[MCPDF_MAX_CW_PER_ROW];
    int cluster;
} McpdfBand;

/* 96-bit (3x32) unsigned big-number accumulator: value*928+add, MSB-first
 * bit extraction. A single MicroPDF417/CC-A "group" is at most 7 codewords
 * (values 0..928), whose base-928 value needs at most 69 bits -- 96 bits of
 * headroom is ample and keeps the arithmetic simple (no >64-bit type
 * dependency). */
typedef struct { uint32_t w[3]; } Mcpdf96;

static void mcpdf96_zero(Mcpdf96 *a) { a->w[0] = a->w[1] = a->w[2] = 0; }

static void mcpdf96_muladd(Mcpdf96 *a, uint32_t mul, uint32_t add)
{
    uint64_t carry = add;
    for (int i = 0; i < 3; i++) {
        uint64_t v = (uint64_t)a->w[i] * mul + carry;
        a->w[i] = (uint32_t)(v & 0xFFFFFFFFu);
        carry = v >> 32;
    }
}

/* bit_from_msb: 0 = most significant bit of the `total_bits`-bit number. */
static int mcpdf96_get_bit(const Mcpdf96 *a, int bit_from_msb, int total_bits)
{
    int bit_index = total_bits - 1 - bit_from_msb;
    if (bit_index < 0) return 0;
    int word = bit_index / 32;
    int off = bit_index % 32;
    if (word > 2) return 0;
    return (int)((a->w[word] >> off) & 1u);
}

/* ── GS1 Composite CC-A "general field" bit decodation ───────────────── */

typedef struct {
    const int *bits;
    int len;
    int pos;
} McpdfBitReader;

static int mcpdf_br_take(McpdfBitReader *br, int n, int *out_val)
{
    if (br->pos + n > br->len) return 0;
    int v = 0;
    for (int i = 0; i < n; i++) v = (v << 1) | br->bits[br->pos + i];
    br->pos += n;
    if (out_val) *out_val = v;
    return 1;
}

static int mcpdf_br_peek_zero(McpdfBitReader *br, int n)
{
    if (br->pos + n > br->len) return 0;
    for (int i = 0; i < n; i++) {
        if (br->bits[br->pos + i] != 0) return 0;
    }
    return 1;
}

/* Three-mode (Numeric / Alphanumeric / ISO646) general-purpose field
 * decodation shared by AI(90) (Method 3) and plain (Method 1) fields.
 * Validated bit-for-bit against three independent samples (see Section 9
 * header comment). Runs until the bitstream is exhausted (any remaining
 * bits too short for the next code are trailing pad, not an error) or an
 * FNC1 codeword is seen (treated as a clean field terminator). */
typedef enum { MCPDF_MODE_NUM, MCPDF_MODE_ALNUM, MCPDF_MODE_ISO646 } McpdfFieldMode;

static void mcpdf_general_field_decode(McpdfBitReader *br, Pdf417Out *out, McpdfFieldMode start_mode)
{
    static const char PUNCT6[5] = { '*', ',', '-', '.', '/' };
    McpdfFieldMode mode = start_mode;
    enum { MODE_NUM = MCPDF_MODE_NUM, MODE_ALNUM = MCPDF_MODE_ALNUM, MODE_ISO646 = MCPDF_MODE_ISO646 };

    for (;;) {
        if (mode == MODE_NUM) {
            if (mcpdf_br_peek_zero(br, 4)) {
                br->pos += 4;
                mode = MODE_ALNUM;
                continue;
            }
            int v7;
            if (!mcpdf_br_take(br, 7, &v7)) break;
            int cv = v7 - 8;
            if (cv >= 0 && cv <= 120) {
                int d1 = cv / 11, d2 = cv % 11;
                if (d1 <= 9) pdf417_out_putc(out, (char)('0' + d1));
                if (d2 <= 9) pdf417_out_putc(out, (char)('0' + d2));
                else if (d2 == 10) { /* FNC1 digit pair terminator */ }
            }
        } else if (mode == MODE_ALNUM) {
            if (mcpdf_br_peek_zero(br, 3)) {
                br->pos += 3;
                mode = MODE_NUM;
                continue;
            }
            int v5;
            if (!mcpdf_br_take(br, 5, &v5)) break;
            if (v5 == 4) { mode = MODE_ISO646; continue; }
            if (v5 == 15) break; /* FNC1 */
            if (v5 >= 5 && v5 <= 14) { pdf417_out_putc(out, (char)('0' + (v5 - 5))); continue; }
            if (v5 >= 16) {
                int b6;
                if (!mcpdf_br_take(br, 1, &b6)) break;
                int v6 = v5 * 2 + b6;
                if (v6 >= 32 && v6 <= 57) pdf417_out_putc(out, (char)(v6 + 33));
                else if (v6 >= 58 && v6 <= 62) pdf417_out_putc(out, PUNCT6[v6 - 58]);
                continue;
            }
            break;
        } else { /* MODE_ISO646 */
            if (mcpdf_br_peek_zero(br, 3)) {
                br->pos += 3;
                mode = MODE_NUM;
                continue;
            }
            int v5;
            if (!mcpdf_br_take(br, 5, &v5)) break;
            if (v5 == 4) { mode = MODE_ALNUM; continue; }
            if (v5 == 15) break; /* FNC1 */
            if (v5 >= 5 && v5 <= 14) { pdf417_out_putc(out, (char)('0' + (v5 - 5))); continue; }
            if (v5 >= 16) {
                int e2;
                if (!mcpdf_br_take(br, 2, &e2)) break;
                int v7 = v5 * 4 + e2;
                if (v7 >= 64 && v7 <= 89) pdf417_out_putc(out, (char)(v7 + 1));       /* uppercase, c-1 */
                else if (v7 >= 90 && v7 <= 115) pdf417_out_putc(out, (char)(v7 + 7)); /* lowercase, c-7 */
                continue;
            }
            break;
        }
    }
}

/* CC-A data field header: leading '0' = Method 1 (general field starts
 * directly, in Numeric mode); leading "11" = Method 3 (AI(90) compressed
 * header: 2-bit method + 1-2 bit sub-mode + 1-bit crop + 5(+10)-bit value +
 * 4-bit letter, then the general field continues in Alphanumeric mode).
 * Leading "10" is a third method (not exercised by the target sample set,
 * left unimplemented per the design note) -- decode fails cleanly. */
static int mcpdf_cca_decode_bits(const int *bits, int total_bits, char *out_buf, int out_cap)
{
    Pdf417Out out;
    out.buf = out_buf;
    out.len = 0;
    out.cap = out_cap;
    out_buf[0] = '\0';
    if (total_bits < 1) return 0;

    McpdfBitReader br;
    br.bits = bits;
    br.len = total_bits;
    br.pos = 0;

    if (bits[0] == 0) {
        br.pos = 1;
        mcpdf_general_field_decode(&br, &out, MCPDF_MODE_NUM);
        return out.len;
    }

    if (total_bits >= 2 && bits[0] == 1 && bits[1] == 1) {
        br.pos = 2;
        int mode_bit;
        if (!mcpdf_br_take(&br, 1, &mode_bit)) return 0;
        int submode = 0; /* 0 = alnum (validated), 1 = numeric, 2 = alpha (unsupported) */
        if (mode_bit != 0) {
            int b2;
            if (!mcpdf_br_take(&br, 1, &b2)) return 0;
            submode = (b2 == 0) ? 1 : 2;
        }
        if (submode != 0) return 0;

        int crop_bit;
        if (!mcpdf_br_take(&br, 1, &crop_bit)) return 0;
        int val5;
        if (!mcpdf_br_take(&br, 5, &val5)) return 0;
        int value = val5;
        if (val5 == 31) {
            int val10;
            if (!mcpdf_br_take(&br, 10, &val10)) return 0;
            value = val10;
        }
        int letter_idx;
        if (!mcpdf_br_take(&br, 4, &letter_idx)) return 0;
        static const char LETTER_TBL[16] = {
            'B', 'D', 'H', 'I', 'J', 'K', 'L', 'N',
            'P', 'Q', 'R', 'S', 'T', 'V', 'W', 'Z',
        };
        if (letter_idx < 0 || letter_idx >= 16) return 0;

        pdf417_out_putc(&out, '9');
        pdf417_out_putc(&out, '0');
        char numbuf[16];
        int nlen = snprintf(numbuf, sizeof(numbuf), "%d", value);
        for (int i = 0; i < nlen; i++) pdf417_out_putc(&out, numbuf[i]);
        pdf417_out_putc(&out, LETTER_TBL[letter_idx]);

        mcpdf_general_field_decode(&br, &out, MCPDF_MODE_ALNUM);
        return out.len;
    }

    return 0; /* Method 2 ("10" prefix): not implemented */
}

/* ── Row/geometry scan + per-layout decode driver ────────────────────── */

static int micropdf_try_layout(const Image *img, int thresh, const McpdfLayout *layout,
                                BarcodeResult *result)
{
    int H = img->height;
    McpdfBand *bands = (McpdfBand *)malloc(sizeof(McpdfBand) * (size_t)H);
    if (!bands) return 0;
    int n_bands = 0;
    McpdfBand prev;
    int have_prev = 0;
    int modbits[MCPDF_MAX_MODULES];

    for (int y = 0; y < H; y++) {
        if (!mcpdf_row_module_bits(img, y, thresh, layout->total_modules, modbits)) {
            have_prev = 0;
            continue;
        }
        int pos = 0, ncw = 0, cluster = -1, ok = 1;
        int cw[MCPDF_MAX_CW_PER_ROW];
        for (int s = 0; s < layout->n_segs; s++) {
            int len = layout->seg_len[s];
            if (layout->seg_is_cw[s]) {
                uint32_t val = 0;
                for (int k = 0; k < len; k++) val = (val << 1) | (uint32_t)modbits[pos + k];
                int clu = -1;
                int v = pdf417_symbol_table_lookup(val, &clu);
                if (v < 0) { ok = 0; break; }
                if (cluster < 0) cluster = clu;
                else if (cluster != clu) { ok = 0; break; }
                if (ncw >= MCPDF_MAX_CW_PER_ROW) { ok = 0; break; }
                cw[ncw++] = v;
            }
            pos += len;
        }
        if (!ok || ncw != layout->ncw_per_row) {
            have_prev = 0;
            continue;
        }
        if (have_prev && prev.cluster == cluster &&
            memcmp(prev.cw, cw, sizeof(int) * (size_t)ncw) == 0) {
            continue; /* same physical row as the previous matched pixel row */
        }
        if (n_bands < H) {
            memcpy(bands[n_bands].cw, cw, sizeof(int) * (size_t)ncw);
            bands[n_bands].cluster = cluster;
            n_bands++;
        }
        memcpy(prev.cw, cw, sizeof(int) * (size_t)ncw);
        prev.cluster = cluster;
        have_prev = 1;
    }

    if (n_bands < 2) { free(bands); return 0; }

    int ec = 0, bitcap = 0;
    if (!mcpdf_lookup_variant(layout->variants, layout->n_variants, n_bands, &ec, &bitcap)) {
        free(bands);
        return 0;
    }

    int total_cw = n_bands * layout->ncw_per_row;
    if (total_cw < 1 || total_cw > PDF417_MAX_CW) { free(bands); return 0; }
    int *codewords = (int *)malloc(sizeof(int) * (size_t)total_cw);
    if (!codewords) { free(bands); return 0; }
    for (int i = 0; i < n_bands; i++) {
        for (int k = 0; k < layout->ncw_per_row; k++) {
            codewords[i * layout->ncw_per_row + k] = bands[i].cw[k];
        }
    }
    free(bands);

    int confidence = 0;
    if (!pdf417_rs_correct_and_score_ex(codewords, total_cw, ec, NULL, 0, &confidence)) {
        free(codewords);
        return 0;
    }

    int data_len = total_cw - ec;
    if (data_len < 1) { free(codewords); return 0; }

    char textbuf[BARCODE_MAX_LEN];
    int outlen;
    if (layout->is_cca) {
        int bits[256];
        int bitpos = 0;
        int i = 0;
        int nfull = data_len / 7;
        int remainder = data_len % 7;
        for (int g = 0; g < nfull; g++) {
            Mcpdf96 acc;
            mcpdf96_zero(&acc);
            for (int k = 0; k < 7; k++) mcpdf96_muladd(&acc, 928, (uint32_t)codewords[i + k]);
            for (int b = 0; b < 69 && bitpos < 256; b++) bits[bitpos++] = mcpdf96_get_bit(&acc, b, 69);
            i += 7;
        }
        if (remainder > 0) {
            int last_bits = bitcap - 69 * nfull;
            if (last_bits < 0) last_bits = 0;
            if (last_bits > 96) last_bits = 96;
            Mcpdf96 acc;
            mcpdf96_zero(&acc);
            for (int k = 0; k < remainder; k++) mcpdf96_muladd(&acc, 928, (uint32_t)codewords[i + k]);
            for (int b = 0; b < last_bits && bitpos < 256; b++) {
                bits[bitpos++] = mcpdf96_get_bit(&acc, b, last_bits);
            }
            i += remainder;
        }
        outlen = mcpdf_cca_decode_bits(bits, bitpos, textbuf, (int)sizeof(textbuf));
    } else {
        outlen = pdf417_decode_text_micro(codewords, data_len, textbuf, (int)sizeof(textbuf));
    }
    free(codewords);
    if (outlen <= 0) return 0;

    memset(result, 0, sizeof(*result));
    int copy_len = outlen < BARCODE_MAX_LEN - 1 ? outlen : BARCODE_MAX_LEN - 1;
    memcpy(result->data, textbuf, (size_t)copy_len);
    result->data[copy_len] = '\0';
    result->length = copy_len;
    result->confidence = confidence;
    result->symbology = BARCODE_SYM_PDF417;
    return 1;
}

int micropdf417_decode(const Image *img, BarcodeResult *result)
{
    if (!img || !result || !img->pixels || img->width <= 0 || img->height <= 0) {
        if (result) memset(result, 0, sizeof(*result));
        return 0;
    }
    memset(result, 0, sizeof(*result));

    int thresh = pdf417_otsu_threshold(img);
    for (size_t li = 0; li < sizeof(MCPDF_LAYOUTS) / sizeof(MCPDF_LAYOUTS[0]); li++) {
        if (micropdf_try_layout(img, thresh, &MCPDF_LAYOUTS[li], result)) return 1;
    }

    Image flipped;
    if (pdf417_clone_hflip(img, &flipped) == 0) {
        int thresh2 = pdf417_otsu_threshold(&flipped);
        for (size_t li = 0; li < sizeof(MCPDF_LAYOUTS) / sizeof(MCPDF_LAYOUTS[0]); li++) {
            if (micropdf_try_layout(&flipped, thresh2, &MCPDF_LAYOUTS[li], result)) {
                free(flipped.pixels);
                return 1;
            }
        }
        free(flipped.pixels);
    }

    memset(result, 0, sizeof(*result));
    return 0;
}
